import { defineConfig } from 'tsup';
import fs from 'fs';
import path from 'path';

export default defineConfig({
    entry: ['src/main.ts'],
    format: ['esm'], // пусть tsup генерит export {...}
    outDir: '../luci-app-postq/htdocs/luci-static/resources/view/postq',
    outExtension: () => ({ js: '.js' }),
    dts: false,
    clean: false,
    sourcemap: false,
    // The routers have little flash: the bundle is installed minified.
    minify: true,
    banner: {
        js: `// This file is autogenerated, please don't change manually \n"use strict";`,
    },
    esbuildOptions(options) {
        options.legalComments = 'none';
    },
    onSuccess: () => {
        const outDir =
            '../luci-app-postq/htdocs/luci-static/resources/view/postq';
        const file = path.join(outDir, 'main.js');
        let code = fs.readFileSync(file, 'utf8');

        // A minified bundle exports its names as "a as Name": in the object
        // literal for LuCI they become "Name: a".
        code = code.replace(
            /export\s*{([\s\S]*?)}/,
            (match, group) => {
                const members = group
                    .split(',')
                    .map((item) => item.trim())
                    .filter(Boolean)
                    .map((item) => {
                        const [local, exported] = item.split(/\s+as\s+/);

                        return exported ? `${exported}:${local}` : local;
                    });

                // The backend reads the installed version out of this file by
                // the name (get_luci_app_version), which the minifier renames.
                return `var POSTQ_LUCI_APP_VERSION = "__COMPILED_VERSION_VARIABLE__";\nreturn baseclass.extend({${members.join(',')}})`;
            }
        );

        fs.writeFileSync(file, code, 'utf8');
        console.log(`✅ Patched LuCI build: ${file}`);
    },
});
